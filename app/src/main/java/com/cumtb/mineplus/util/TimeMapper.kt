package com.cumtb.mineplus.util

object TimeMapper {

    /**
     * 将物理时间 (HHmm) 映射为 逻辑节次 (1-12)
     *
     * 策略：时间桶 (Time Buckets)
     * 目的：兼容学院路校区、沙河校区不同教学楼的作息时间差异
     *
     * @param startTime 例如 800, 955, 1330
     * @return 节次 (1~12)，如果匹配不到返回 -1
     */
    fun mapStartTimeToNode(startTime: Int): Int {
        return when (startTime) {
            // === 上午 (Morning) ===
            // 第1节 (标准 08:00) -> 捕获 < 08:30
            in 0..830 -> 1

            // 第2节 (标准 08:50) -> 捕获 08:30 - 09:20
            in 831..920 -> 2

            // 第3节 (差异最大: 09:50, 09:55, 10:10) -> 捕获 09:21 - 10:25
            in 921..1025 -> 3

            // 第4节 (差异: 10:40, 10:45, 11:00) -> 捕获 10:26 - 12:00
            in 1026..1200 -> 4

            // === 下午 (Afternoon) ===
            // 第5节 (标准 13:30) -> 捕获 12:01 - 14:00
            in 1201..1400 -> 5

            // 第6节 (标准 14:20) -> 捕获 14:01 - 14:50
            in 1401..1450 -> 6

            // 第7节 (标准 15:20) -> 捕获 14:51 - 15:50
            in 1451..1550 -> 7

            // 第8节 (标准 16:10) -> 捕获 15:51 - 16:40
            in 1551..1640 -> 8

            // 第9节 (标准 17:00) -> 捕获 > 16:40
            in 1641..1800 -> 9

            // === 晚上 (Evening) ===
            // 第10节 (标准 19:00) -> 捕获 18:01 - 19:30
            in 1801..1930 -> 10

            // 第11节 (标准 19:50) -> 捕获 19:31 - 20:20
            in 1931..2020 -> 11

            // 第12节 (标准 20:40) -> 捕获 > 20:20
            in 2021..2400 -> 12

            else -> 1 // 兜底，实在解析不了就算第1节，防止崩溃
        }
    }
}
